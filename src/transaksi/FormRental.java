    private void tblRentalMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblRentalMouseClicked
        int row = tblRental.getSelectedRow();
        if (row == -1) return;

        txtIdRental.setText(tblRental.getValueAt(row, 0).toString());
        cbMobil.setSelectedItem(tblRental.getValueAt(row, 1).toString());
        cbPelanggan.setSelectedItem(tblRental.getValueAt(row, 2).toString());
        cbKaryawan.setSelectedItem(tblRental.getValueAt(row, 3).toString());
        dcTglSewa.setDate(java.sql.Date.valueOf(tblRental.getValueAt(row, 4).toString()));
        dcTglKembali.setDate(java.sql.Date.valueOf(tblRental.getValueAt(row, 5).toString()));
        txtTotal.setText(tblRental.getValueAt(row, 6).toString());
    }//GEN-LAST:event_tblRentalMouseClicked

