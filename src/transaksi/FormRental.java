    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
         if (txtIdRental.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih data dari tabel!");
            return;
        }
        
        try{
             String sql = "DELETE FROM rental WHERE id_rental=?";
            PreparedStatement ps = Koneksi.getConnection().prepareStatement(sql);
            ps.setInt(1, Integer.parseInt(txtIdRental.getText()));
            ps.executeUpdate();
             JOptionPane.showMessageDialog(null, "Data rental dihapus");
            tampilData();
        }catch (Exception e) {
           JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try{
            if (dcTglSewa.getDate() == null || dcTglKembali.getDate() == null){
                JOptionPane.showMessageDialog(this, "Tanggal belum dipilih");
                return;
            }
            
            String sql = "INSERT INTO rental (no_plat,no_ktp,karyawan,tgl_sewa,tgl_kembali,total_bayar) VALUES (?,?,?,?,?,?)";
            PreparedStatement ps = Koneksi.getConnection().prepareStatement(sql);
            ps.setString(1, cbMobil.getSelectedItem().toString());
            ps.setString(2, cbPelanggan.getSelectedItem().toString());
            
            ps.setString(3, cbKaryawan.getSelectedItem().toString());
            ps.setDate(4, new java.sql.Date(dcTglSewa.getDate().getTime()));
            ps.setDate(5, new java.sql.Date(dcTglKembali.getDate().getTime()));
            ps.setInt(6, Integer.parseInt(txtTotal.getText()));
            ps.executeUpdate();
            
           
            tampilData();
            JOptionPane.showMessageDialog(null, "Data Rental berhasil disimpan");
        }catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if (txtIdRental.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih data dari tabel!");
        return;
    }
        
        try{
            String sql = "UPDATE rental SET no_plat=?,no_ktp=?,karyawan=?,tgl_sewa=?,tgl_kembali=?,total_bayar=? WHERE id_rental=?";
            PreparedStatement ps = Koneksi.getConnection().prepareStatement(sql);
            ps.setString(1, cbMobil.getSelectedItem().toString());
            ps.setString(2, cbPelanggan.getSelectedItem().toString());
            ps.setString(3, cbKaryawan.getSelectedItem().toString());
            ps.setDate(4, new java.sql.Date(dcTglSewa.getDate().getTime()));
            ps.setDate(5, new java.sql.Date(dcTglKembali.getDate().getTime()));
            ps.setInt(6, Integer.parseInt(txtTotal.getText()));
            ps.setInt(7, Integer.parseInt(txtIdRental.getText()));
            ps.executeUpdate();
            
            JOptionPane.showMessageDialog(null, "Data rental diubah");
            tampilData();
        }catch (Exception e){
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnUbahActionPerformed

