    void isiComboMobil() {
    cbMobil.removeAllItems();
    try {
        Connection c = Koneksi.getConnection();
        Statement s = c.createStatement();
        ResultSet rs = s.executeQuery("SELECT no_plat FROM mobil");

        while (rs.next()) {
            cbMobil.addItem(rs.getString("no_plat"));
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, e.getMessage());
    }
}

// Method untuk menampilkan data mobil dari database ke JTable
void tampilData(){
    // Membuat model tabel baru
    DefaultTableModel model = new DefaultTableModel();
    
    // Menambahkan kolom ke tabel

        model.addColumn("ID");
        model.addColumn("Mobil");
        model.addColumn("Pelanggan");
        model.addColumn("Karyawan");
        model.addColumn("Tgl Sewa");
        model.addColumn("Tgl Kembali");
        model.addColumn("Total");
        
        try{
        Connection c = Koneksi.getConnection(); // Membuka koneksi database
        Statement st = c.createStatement();// Membuat statement
           
            ResultSet rs = st.executeQuery("SELECT * FROM rental");// Query mengambil seluruh data mobil
            while (rs.next()){// Perulangan untuk membaca data
                model.addRow(new Object[]{
                    rs.getInt("id_rental"),
                    rs.getString("no_plat"),
                    rs.getString("no_ktp"),
                    rs.getString("karyawan"),
                    rs.getDate("tgl_sewa"),
                    rs.getDate("tgl_kembali"),
                    rs.getInt("total_bayar")
                });
            }
            tblRental.setModel(model);
        }catch (Exception e){
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
}
