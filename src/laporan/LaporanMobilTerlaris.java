    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
                                                   
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("No Plat");
    model.addColumn("Merek");
    model.addColumn("Total Disewa");

    try {
        Connection c = Koneksi.getConnection();
        if (c == null) {
            JOptionPane.showMessageDialog(this, "Koneksi database gagal!");
            return;
        }

        String sql =
            "SELECT m.no_plat, m.merek, COUNT(r.id_rental) AS total_disewa " +
            "FROM rental r " +
            "JOIN mobil m ON r.no_plat = m.no_plat " +
            "GROUP BY m.no_plat, m.merek " +
            "ORDER BY total_disewa DESC";

        Statement s = c.createStatement();
        ResultSet rs = s.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("no_plat"),
                rs.getString("merek"),
                rs.getInt("total_disewa") // ✅ BENAR
            });
        }

        tblLaris.setModel(model);

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                "Data rental ada, tapi NO PLAT tidak cocok dengan tabel mobil!");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnGenerateActionPerformed

