    private void btnExportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportActionPerformed
        if (tblLaris.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Data laporan masih kosong");
            return;
        }

        try {
            JFileChooser fc = new JFileChooser();
            fc.setSelectedFile(new File("laporan_mobil_terlaris.txt"));

            if (fc.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
                FileWriter fw = new FileWriter(fc.getSelectedFile());
                DefaultTableModel model = (DefaultTableModel) tblLaris.getModel();

                for (int i = 0; i < model.getRowCount(); i++) {
                    fw.write(
                        model.getValueAt(i, 0) + " | " +
                        model.getValueAt(i, 1) + " | " +
                        model.getValueAt(i, 2) + "\n"
                    );
                }
             fw.close();
                JOptionPane.showMessageDialog(this, "Export berhasil");
            }
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnExportActionPerformed

