    void tampilData(){
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("No Plat");
        model.addColumn("Merek");
        model.addColumn("Tipe");
        model.addColumn("Harga");
        model.addColumn("Status");
        
        try{
            
            String sql = "SELECT * FROM mobil";
        Connection c = Koneksi.getConnection();
        
        if (c == null) {
            JOptionPane.showMessageDialog(this, "Koneksi database NULL");
            return;
        }
           
            Statement st = c.createStatement();
            ResultSet rs = st.executeQuery(sql);
            
            while (rs.next()){
                model.addRow(new Object[]{
                    rs.getString("no_plat"),
                    rs.getString("merek"),
                    rs.getString("tipe"),
                    rs.getInt("harga_sewa"),
                    rs.getString("status")
                });
            }
            tblMobil.setModel(model);
        }catch (Exception e){
                JOptionPane.showMessageDialog(this, "Error tampil data: " + e.getMessage());

        }
    }
