    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
       try{
           String sql = "INSERT INTO mobil VALUES (?,?,?,?,?)";
            PreparedStatement ps = Koneksi.getConnection().prepareStatement(sql);
            ps.setString(1, txtPlat.getText());
            ps.setString(2, txtMerek.getText());
            ps.setString(3, txtTipe.getText());
            ps.setInt(4, Integer.parseInt(txtHarga.getText()));
            ps.setString(5, cbStatus.getSelectedItem().toString());
            ps.executeUpdate();
            
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
            tampilData();
       }catch (Exception e){
           JOptionPane.showMessageDialog(null, e.getMessage());

       }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        try{
            String sql = "UPDATE mobil SET merek=?, tipe=?, harga_sewa=?, status=? WHERE no_plat=?";
        PreparedStatement ps = Koneksi.getConnection().prepareStatement(sql);
        ps.setString(1, txtMerek.getText());
        ps.setString(2, txtTipe.getText());
        ps.setInt(3, Integer.parseInt(txtHarga.getText()));
        ps.setString(4, cbStatus.getSelectedItem().toString());
        ps.setString(5, txtPlat.getText());
        ps.executeUpdate();
        
        JOptionPane.showMessageDialog(null, "Data berhasil diubah");
        tampilData();
        
        }catch (Exception e){
           JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (txtPlat.getText().isEmpty()){
         JOptionPane.showMessageDialog(this, "Pilih data dari tabel!");
        return;
        }
            
        try{
        String sql = "DELETE FROM mobil WHERE no_plat=?";
        PreparedStatement ps = Koneksi.getConnection().prepareStatement(sql);
        ps.setString(1, txtPlat.getText());
        ps.executeUpdate();
        
        JOptionPane.showMessageDialog(null, "Data berhasil dihapus");
        tampilData();
        }catch (Exception e){
           JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnHapusActionPerformed

